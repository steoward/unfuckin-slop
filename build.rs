//! Bakes the card library into the binary so `slop` works with no install step.
//! Zero dependencies: this is all the "build system" the project needs.

use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let cards_dir = manifest.join("skills/unfuckin-slop/cards");
    println!("cargo:rerun-if-changed={}", cards_dir.display());
    println!("cargo:rerun-if-changed=skills/unfuckin-slop/SKILL.md");

    let mut files: Vec<PathBuf> = fs::read_dir(&cards_dir)
        .expect("skills/unfuckin-slop/cards must exist")
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().map(|x| x == "md").unwrap_or(false))
        .collect();
    files.sort();

    let mut out = String::from("// @generated by build.rs\n");
    out.push_str("pub static CARDS: &[(&str, &str)] = &[\n");
    for path in &files {
        let stem = path.file_stem().unwrap().to_string_lossy();
        let rel = path
            .strip_prefix(&manifest)
            .unwrap()
            .to_string_lossy()
            .replace(std::path::MAIN_SEPARATOR, "/");
        out.push_str(&format!("    ({stem:?}, include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/{rel}\"))),\n"));
    }
    out.push_str("];\n\n");
    out.push_str(
        "pub static SKILL_MD: &str = include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/skills/unfuckin-slop/SKILL.md\"));\n",
    );

    fs::write(Path::new(&std::env::var("OUT_DIR").unwrap()).join("embedded.rs"), out).unwrap();
}
