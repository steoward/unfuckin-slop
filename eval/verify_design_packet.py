"""Test the installed CLI with a small public-safe catalog."""
from base64 import b64decode
from hashlib import sha256
import json
import os
from pathlib import Path
import subprocess
import sys
from tempfile import TemporaryDirectory

PNG = b64decode("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jf7sAAAAASUVORK5CYII=")


def record(key, title, source, category, description, body=""):
    return dict(id=key, title=title, source_site=source, source_url=f"https://{source}/{key}",
                category=category, type="hero" if category == "Hero" else category.lower(),
                description=description, full_prompt=body)


def test_cli(binary, location):
    prompt = "  Build a two-column recorder page with a waveform timeline.\r\n" + "♪" * 600 + "\n\n"
    files = {
        "components/cards.tsx": "  export const Cards = () => <section>Cartes é</section>;\n",
        "components/cards.css": ".cards { display: grid; }\n\n",
    }
    snapshot = "Example component\n\n" + "\n".join(
        f"--- file: {path} ---\n```{'tsx' if path.endswith('.tsx') else 'css'}\n{text}```\n"
        for path, text in files.items()
    )
    media_root = location / "media"
    media_root.mkdir()
    preview = media_root / "sound-atlas.png"
    preview.write_bytes(PNG)
    preview_digest = sha256(preview.read_bytes()).hexdigest()
    designs = [
        record("sound-atlas", "Sound Atlas", "motionsites.ai", "Hero",
               "Browse field recordings with a waveform timeline",
               prompt),
        record("plain-footer", "Plain Footer", "motionsites.ai", "Footer",
               "Links and contact information in a small site footer", "Use a footer nav."),
    ]
    designs[0]["media"] = [{"kind": "image", "path": preview.name, "sha256": preview_digest,
                            "rights": "Original fixture generated by this test"}]
    components = [
        record("sample-swipe", "Swiping Cards", "skiper-ui.com", "Carousel",
               "Drag stacked photo cards horizontally",
               snapshot),
        record("sample-nav", "Navbar", "21st.dev", "Navigation",
               "Responsive navigation with mobile menu",
               'Install: npx shadcn@latest add "https://21st.dev/r/example/nav?api_key=$API_KEY_21ST"'),
    ]
    for name, rows in (("showcases", designs), ("components", components)):
        (location / f"{name}_meta.json").write_text(json.dumps(rows), encoding="utf-8")
    env = {**os.environ, "UNFSLOP_LIBRARY_DATA": str(location), "UNFSLOP_MEDIA_ROOT": str(media_root)}

    def run(*args):
        return json.loads(subprocess.check_output([binary, *args], env=env, encoding="utf-8"))

    def check_delivery(item, expected, tier):
        delivery = item["delivery"]
        encoded = expected.encode("utf-8")
        assert delivery["tier"] == tier, delivery
        assert delivery["payload"] == expected
        assert delivery["payload_bytes"] == len(encoded)
        assert delivery["payload_sha256"] == sha256(encoded).hexdigest()
        return delivery

    page = run("library", "--limit", "2")
    assert page["total"] == 4 and page["next_offset"] == 2
    assert run("library", "--offset", "2")["next_offset"] is None
    hit = run("library", "stacked photo cards", "--source", "skiper-ui.com")
    assert hit["backends"] == {"components": "lexical"}
    assert hit["items"][0]["id"] == "sample-swipe"
    assert "payload" not in hit["items"][0]["delivery"]
    assert "inspection" not in hit["items"][0]
    full_hit = run("library", "sample-swipe", "--full")["items"][0]
    source = check_delivery(full_hit, snapshot, "source_snapshot")
    assert source["source_file_count"] == len(files)
    assert source["requires_reconstruction"] is False
    assert source["files"] == [
        {"path": path, "content": content, "sha256": sha256(content.encode("utf-8")).hexdigest()}
        for path, content in files.items()
    ]
    items = run("library", "--record", "sound-atlas", "--record", "sample-nav")["items"]
    assert [item["record"] for item in items] == [designs[0], components[1]]
    assert items[1]["use"]["registry_url"] == "https://21st.dev/r/example/nav"
    spec = check_delivery(items[0], prompt, "build_specification")
    assert spec["files"] == [] and spec["requires_reconstruction"]
    assert items[0]["inspection"] == {
        "status": "verified",
        "preview": {"path": str(preview.resolve()), "sha256": preview_digest, "kind": "original_image"},
    }
    registry = check_delivery(items[1], components[1]["full_prompt"], "registry_pointer")
    assert registry["files"] == [] and registry["source_file_count"] == 0
    assert registry["requires_reconstruction"] is True
    plan = run("plan", "Field recordings with a waveform timeline",
               "--section", "carousel=sample-swipe")
    assert plan["status"] == "ok" and plan["blueprint"]["selected"]["id"] == "sound-atlas"
    assert plan["sections"][0]["selected"]["record"] == components[0]
    check_delivery(plan["blueprint"]["selected"], prompt, "build_specification")
    assert check_delivery(plan["sections"][0]["selected"], snapshot, "source_snapshot") == source
    evidence = run("design", "sound-atlas")["evidence"]
    assert evidence["backend"] == "catalog_exact"
    assert Path(evidence["references"][0]["visual_evidence"]["path"]) == preview.resolve()
    preview.write_bytes(PNG + b"changed bytes")
    changed = run("library", "--record", "sound-atlas")["items"][0]
    assert check_delivery(changed, prompt, "build_specification") == spec
    inspection = changed["inspection"]
    assert inspection["status"] == "unavailable" and "preview" not in inspection
    assert "Original asset changed" in inspection["reason"]
    print("Verified browse, exact delivery, source extraction, registry pointers and preview integrity.")


if __name__ == "__main__":
    with TemporaryDirectory() as directory:
        test_cli(str(Path(sys.argv[1]).resolve()), Path(directory))
